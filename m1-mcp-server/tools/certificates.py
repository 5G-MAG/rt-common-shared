"""
Server Certificate tools — Maf_Provisioning_ServerCertificates (TS 26.510 V19.2.0 clause 5.2.4)
Endpoints (base path /3gpp-maf-provisioning/v1/provisioning-sessions/{id}):
  POST   /certificates                    create a certificate generated by the Media Delivery System (201, no body)
  POST   /certificates?csr=true           reserve a certificate and get a Certificate Signing Request (201; body: aliases as a JSON array)
  PUT    /certificates/{certificateId}    upload the signed certificate (application/x-pem-file, 204)
  GET    /certificates/{certificateId}    retrieve (200; 204 until the certificate is available)
  DELETE /certificates/{certificateId}    destroy (204; 200 when reserved and never uploaded; 409 while a distribution refers to it)
"""

import json

from mcp_instance import mcp
import m1_http
from . import _common

PEM = "application/x-pem-file"


@mcp.tool()
async def create_server_certificate(provisioning_session_id: str = None, m1_url: str = None) -> str:
    """
    Create a Server Certificate generated by the Media Delivery System operator (POST .../certificates, no request body, 201).

    The Common Name and the single Subject Alternative Name are assigned in a domain of the operator; domain name aliases are not
    supported here (use reserve_server_certificate). The certificate may not be available at once: get_server_certificate answers 204 until
    it is. Reference the returned ID as certificateId in a distribution configuration.

    PARAMETERS
    ----------
    provisioning_session_id (OPTIONAL)  The session; the one in the current state when omitted.
    m1_url (OPTIONAL if already provided)  Base URL of the M1 interface.
    """
    err = _common.prepare(m1_url, provisioning_session_id)
    if err:
        return err
    return (await _common.create(m1_http.session_path(provisioning_session_id, "certificates"), None, "Server Certificate",
                                 id_label="Certificate ID"))[1]


@mcp.tool()
async def reserve_server_certificate(domain_name_aliases: list[str] = None, provisioning_session_id: str = None, m1_url: str = None) -> str:
    """
    Reserve a Server Certificate and get a Certificate Signing Request (POST .../certificates?csr=true, 201).

    The provider signs the CSR with its own CA and uploads the certificate with upload_server_certificate. The private key never
    leaves the Media AF. The request body is the JSON array of domain name aliases (included in the CSR as Subject Alternative Names),
    omitted when there are none.

    PARAMETERS
    ----------
    domain_name_aliases (OPTIONAL)  Extra domain names for the Subject Alternative Name extension.
    provisioning_session_id (OPTIONAL)  The session; the one in the current state when omitted.
    m1_url (OPTIONAL if already provided)  Base URL of the M1 interface.

    RETURNS
    -------
    The certificate ID and the CSR in PEM form.
    """
    err = _common.prepare(m1_url, provisioning_session_id)
    if err:
        return err
    out = await m1_http.call("POST", m1_http.session_path(provisioning_session_id, "certificates"),
                             body=list(domain_name_aliases) if domain_name_aliases else None, params={"csr": "true"},
                             accept=f"{PEM}, text/plain, */*", expect=(201,))
    if not out.ok:
        return out.error
    resp = out.response
    return (f"SUCCESS: Server Certificate reserved.\n\n  Certificate ID: {m1_http.last_id(resp)}\n{m1_http.etag_line(resp)}\n"
            f"Certificate Signing Request:\n{resp.text}\n\nNEXT STEP → sign it and call upload_server_certificate")


@mcp.tool()
async def upload_server_certificate(certificate_id: str, certificate_pem: str, provisioning_session_id: str = None, m1_url: str = None) -> str:
    """
    Upload the signed X.509 certificate of a reserved Server Certificate (PUT .../certificates/{certificateId}, application/x-pem-file, 204).

    Only the party that reserved the certificate can upload; 403 when the certificate does not match the CSR, 404 when the
    certificate was not reserved. A certificate cannot be replaced once uploaded.

    PARAMETERS
    ----------
    certificate_id (REQUIRED)  The ID returned by reserve_server_certificate.
    certificate_pem (REQUIRED)  The certificate in PEM form.
    provisioning_session_id (OPTIONAL)  The session; the one in the current state when omitted.
    m1_url (OPTIONAL if already provided)  Base URL of the M1 interface.
    """
    err = _common.prepare(m1_url, provisioning_session_id)
    if err:
        return err
    out = await m1_http.call("PUT", m1_http.session_path(provisioning_session_id, "certificates", certificate_id), body=certificate_pem,
                             content_type=PEM, expect=(204,))
    return out.error or f"SUCCESS: Server Certificate '{certificate_id}' uploaded."


@mcp.tool()
async def get_server_certificate(certificate_id: str, provisioning_session_id: str = None, m1_url: str = None) -> str:
    """
    Retrieve a Server Certificate (GET .../certificates/{certificateId}): 200 with the PEM certificate, 204 while it is not yet available
    (generated by the system) or not yet uploaded (reserved).

    PARAMETERS
    ----------
    certificate_id (REQUIRED)  The certificate ID.
    provisioning_session_id (OPTIONAL)  The session; the one in the current state when omitted.
    m1_url (OPTIONAL if already provided)  Base URL of the M1 interface.
    """
    err = _common.prepare(m1_url, provisioning_session_id)
    if err:
        return err
    out = await m1_http.call("GET", m1_http.session_path(provisioning_session_id, "certificates", certificate_id),
                             accept=f"{PEM}, text/plain, */*", expect=(200, 204))
    if not out.ok:
        return out.error
    if out.response.status_code == 204:
        return f"Server Certificate '{certificate_id}' has no certificate yet (HTTP 204)."
    return f"SUCCESS: Server Certificate '{certificate_id}'\n\n{m1_http.etag_line(out.response)}{out.response.text}"


@mcp.tool()
async def delete_server_certificate(certificate_id: str, if_match: str = None, provisioning_session_id: str = None, m1_url: str = None) -> str:
    """
    Destroy a Server Certificate (DELETE, 204; 200 for a reserved certificate that was never uploaded).

    409 while a Content Hosting Configuration refers to it: remove the reference first.

    PARAMETERS
    ----------
    certificate_id (REQUIRED)  The certificate ID.
    if_match (OPTIONAL)  A strong entity tag obtained earlier (clause 7.1.4.4).
    provisioning_session_id (OPTIONAL)  The session; the one in the current state when omitted.
    m1_url (OPTIONAL if already provided)  Base URL of the M1 interface.
    """
    err = _common.prepare(m1_url, provisioning_session_id)
    if err:
        return err
    return await _common.destroy(m1_http.session_path(provisioning_session_id, "certificates", certificate_id),
                                 f"Server Certificate '{certificate_id}'", if_match, expect=(200, 204))
